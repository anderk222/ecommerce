import { HttpClient, httpResource, HttpResourceRef } from '@angular/common/http';
import { inject, Service } from '@angular/core';
import { Observable } from 'rxjs';

import { API_BASE_URL } from '@core/api/api-base-url';
import { Category } from '@shared/models/catalog.models';

/**
 * The API of the administration of the categories.
 *
 * <p>It lives under `/api/admin`, so every call carries the token of the
 * staff member (HU-13).
 *
 * <p>The read answers in signals (P51); the writes keep their `Observable`.
 */
@Service()
export class AdminCategoriesApi {
  private readonly http = inject(HttpClient);
  private readonly baseUrl = inject(API_BASE_URL);

  /** Every category. */
  list(): HttpResourceRef<Category[] | undefined> {
    return httpResource<Category[]>(() => `${this.baseUrl}/admin/categories`);
  }

  /** Creates a category. The slug is generated by the server. */
  create(name: string): Observable<Category> {
    return this.http.post<Category>(`${this.baseUrl}/admin/categories`, { name });
  }

  /** Renames a category. */
  update(id: number, name: string): Observable<Category> {
    return this.http.put<Category>(`${this.baseUrl}/admin/categories/${id}`, { name });
  }

  /** Deletes a category. The server refuses the ones that still hold items. */
  delete(id: number): Observable<void> {
    return this.http.delete<void>(`${this.baseUrl}/admin/categories/${id}`);
  }
}
